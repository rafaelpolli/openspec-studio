/** An onboarding action that does not fit the job's or capability's state (HTTP 409). */
export class OnboardingStateError extends Error {
  override readonly name = "OnboardingStateError";
}

export const DEFAULT_CONCURRENCY = 3;
const CONCURRENCY_KEY = "onboarding.concurrency";

export interface OnboardingOptions {
  /** App-owned folder where the discovery session writes its JSON (outside every repo). */
  workDir: string;
}

const key = (jobId: string, cap: string) => `${jobId}\u0000${cap}`;

/**
 * Brownfield onboarding (spec: project-onboarding; design D9): discovery → checkpoint →
 * one baseline change per capability, generated by a bounded queue of agent sessions →
 * individual review → batch archive.
 */
export class OnboardingService {
  /** Capabilities with a session in progress, across all jobs (the concurrency budget). */
  readonly #running = new Set<string>();
  /** Cancellations asked for before the capability's session started. */
  readonly #cancelled = new Set<string>();
  /** Bookkeeping that tests and shutdown can wait on. */
  readonly #pending = new Set<Promise<unknown>>();

  constructor(
    private readonly workspaces: WorkspaceService,
    private readonly openspec: OpenSpecAdapter,
    private readonly runner: AgentRunner,
    private readonly repo: OnboardingRepo,
    private readonly db: Database,
    private readonly events: EventBus,
    private readonly opts: OnboardingOptions,
  ) {}

  /** Resumes after a restart: interrupted capabilities go back to the queue (design D9). */
  start(): void {
    this.repo.requeueInterrupted();
    this.repo.failInterruptedDiscovery();
    for (const job of this.repo.generating()) this.#pump(job.id);
  }

  // --- settings --------------------------------------------------------------

  get concurrency(): number {
    const row = this.db.query<{ value: string }, [string]>("SELECT value FROM settings WHERE key = ?").get(CONCURRENCY_KEY);
    const n = row ? Number.parseInt(row.value, 10) : NaN;
    return Number.isInteger(n) && n > 0 ? n : DEFAULT_CONCURRENCY;
  }

  setConcurrency(n: number): number {
    if (!Number.isInteger(n) || n < 1 || n > 16) throw new WorkspaceInputError("a concorrência deve ser um inteiro de 1 a 16");
    this.db
      .query("INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT (key) DO UPDATE SET value = excluded.value")
      .run(CONCURRENCY_KEY, String(n));
    for (const job of this.repo.generating()) this.#pump(job.id);
    return n;
  }

  // --- reads -----------------------------------------------------------------

  current(workspaceId: string): OnboardingJob | null {
    this.workspaces.get(workspaceId);
    return this.repo.latest(workspaceId) ?? null;
  }

  job(jobId: string): OnboardingJob {
    const job = this.repo.get(jobId);
    if (!job) throw new WorkspaceNotFoundError(`job de onboarding não encontrado: ${jobId}`);
    return job;
  }

  /** Waits until no capability or discovery bookkeeping is in flight (tests and shutdown). */
  async settled(): Promise<void> {
    while (this.#pending.size > 0) await Promise.allSettled([...this.#pending]);
  }

  // --- 8.2 discovery ---------------------------------------------------------

  async discover(workspaceId: string): Promise<OnboardingJob> {
    const ws = this.workspaces.get(workspaceId);
    if (needsInit(ws.kind, ws.rootPath)) throw new OnboardingStateError("inicialize o OpenSpec antes da descoberta");
    const previous = this.repo.latest(workspaceId);
    if (previous && ["descobrindo", "gerando"].includes(previous.status)) {
      throw new OnboardingStateError("já existe um onboarding em andamento neste workspace");
    }
    const job = this.repo.create(workspaceId);
    const dir = join(this.opts.workDir, job.id);
    mkdirSync(dir, { recursive: true });
    const output = join(dir, "capabilities.json");
    const prompt = buildDiscoveryPrompt(ws.members, output);
    try {
      const handle = await this.#start(ws, job.discoveryRun, prompt, [dir]);
      this.#track(handle.done.then((run) => this.#finishDiscovery(ws, job.id, run, output)));
    } catch (err) {
      this.repo.setStatus(job.id, "descoberta_falhou", (err as Error).message);
    }
    this.#publish(job);
    return this.job(job.id);
  }

  #finishDiscovery(ws: Workspace, jobId: string, run: RunView, output: string): void {
    const fail = (message: string) => this.repo.setStatus(jobId, "descoberta_falhou", message);
    if (run.status !== "concluido") fail(run.error?.message ?? `a descoberta foi ${run.status}`);
    else if (!existsSync(output)) fail("o agente terminou sem escrever a lista de capacidades");
    else {
      let parsed: unknown;
      try {
        parsed = JSON.parse(readFileSync(output, "utf8"));
      } catch {
        parsed = undefined;
      }
      const checked = DiscoveryFile.safeParse(parsed);
      const problem = checked.success ? listProblem(checked.data.capabilities, ws) : "o JSON da descoberta não segue o formato pedido";
      if (problem) fail(problem);
      else {
        this.repo.setCapabilities(jobId, checked.data!.capabilities);
        this.repo.setStatus(jobId, "checkpoint");
      }
    }
    this.#publishId(ws.id, jobId);
  }

  // --- 8.3 checkpoint and estimate --------------------------------------------

  saveCheckpoint(jobId: string, caps: readonly CapabilityDraft[]): OnboardingJob {
    const job = this.#inStatus(jobId, "checkpoint");
    const problem = listProblem(caps, this.workspaces.get(job.workspaceId));
    if (problem) throw new WorkspaceInputError(problem);
    this.repo.setCapabilities(jobId, caps);
    this.#publish(job);
    return this.job(jobId);
  }

  estimate(jobId: string): Estimate {
    const job = this.#inStatus(jobId, "checkpoint");
    return estimate(job.capabilities, this.workspaces.get(job.workspaceId).members, this.concurrency);
  }

  /** Starts the batch; the caller has shown the estimate and the user confirmed. */
  startBatch(jobId: string): OnboardingJob {
    const job = this.#inStatus(jobId, "checkpoint");
    if (job.capabilities.length === 0) throw new OnboardingStateError("a lista de capacidades está vazia");
    this.repo.setStatus(jobId, "gerando");
    this.#pump(jobId);
    this.#publish(job);
    return this.job(jobId);
  }

  // --- 8.4 executor ------------------------------------------------------------

  retry(jobId: string, cap: string): OnboardingJob {
    const job = this.job(jobId);
    this.#capIn(job, cap, ["falhou", "cancelada"]);
    this.repo.updateCapability(jobId, cap, { status: "aguardando", error: null });
    this.repo.setStatus(jobId, "gerando");
    this.#pump(jobId);
    this.#publish(job);
    return this.job(jobId);
  }

  async cancel(jobId: string, cap: string): Promise<OnboardingJob> {
    const job = this.job(jobId);
    const c = this.#capIn(job, cap, ["aguardando", "gerando"]);
    if (c.status === "aguardando") {
      this.repo.updateCapability(jobId, cap, { status: "cancelada" });
      this.#pump(jobId);
    } else {
      // The generation's own bookkeeping records "cancelada" when the run settles.
      this.#cancelled.add(key(jobId, cap));
      await this.runner.cancel(job.workspaceId, c.changeName ?? baselineName(cap));
    }
    this.#publish(job);
    return this.job(jobId);
  }

  /** Starts queued capabilities while the global concurrency budget allows. */
  #pump(jobId: string): void {
    const job = this.repo.get(jobId);
    if (!job || job.status !== "gerando") return;
    for (const cap of job.capabilities) {
      if (this.#running.size >= this.concurrency) break;
      if (cap.status === "aguardando" && !this.#running.has(key(jobId, cap.name))) {
        this.#track(this.#generate(job, cap));
      }
    }
    const busy = (s: CapabilityStatus) => s === "aguardando" || s === "gerando" || s === "validando";
    const latest = this.repo.get(jobId)!;
    if (!latest.capabilities.some((c) => busy(c.status))) {
      this.repo.setStatus(jobId, "revisao");
      this.#publish(latest);
    }
  }

  async #generate(job: OnboardingJob, cap: Capability): Promise<void> {
    const k = key(job.id, cap.name);
    this.#running.add(k);
    this.#cancelled.delete(k);
    const change = baselineName(cap.name);
    this.repo.updateCapability(job.id, cap.name, { status: "gerando", error: null, changeName: change });
    this.#publish(job);
    try {
      const ws = this.workspaces.get(job.workspaceId);
      const t = target(ws);
      if (!(await this.openspec.listChanges(t)).some((c) => c.name === change)) {
        await this.openspec.newChange(t, change);
      }
      const [proposal, specs, design] = await Promise.all(
        (["proposal", "specs", "design"] as const).map((a) => this.openspec.instructions(t, change, a)),
      );
      const prompt = buildBaselinePrompt(cap, ws.members, { proposal: proposal!, specs: specs!, design: design! });
      await this.#runAndCheck(ws, job, cap.name, change, prompt);
    } catch (err) {
      this.repo.updateCapability(job.id, cap.name, { status: "falhou", error: (err as Error).message });
    } finally {
      this.#running.delete(k);
      this.#cancelled.delete(k);
      this.#publish(job);
      this.#pump(job.id);
    }
  }

  /** Runs one baseline prompt and records the outcome: pronta, falhou or cancelada. */
  async #runAndCheck(ws: Workspace, job: OnboardingJob, cap: string, change: string, prompt: BuiltPrompt) {
    const cancelled = () => this.#cancelled.has(key(job.id, cap));
    const run = cancelled() ? undefined : await (await this.#start(ws, change, prompt)).done;
    if (!run || run.status === "cancelado" || cancelled()) {
      this.repo.updateCapability(job.id, cap, { status: "cancelada", error: null });
      return;
    }
    if (run.status === "falhou") {
      this.repo.updateCapability(job.id, cap, { status: "falhou", error: run.error?.message ?? "o agente falhou" });
      return;
    }
    this.repo.updateCapability(job.id, cap, { status: "validando" });
    this.#publish(job);
    const problem = await this.#checkBaseline(ws, cap, change);
    this.repo.updateCapability(job.id, cap, problem ? { status: "falhou", error: problem } : { status: "pronta", error: null });
  }

  /** What is wrong with a generated baseline, or undefined when it is ready for review. */
  async #checkBaseline(ws: Workspace, cap: string, change: string): Promise<string | undefined> {
    const t = target(ws);
    const status = await this.openspec.status(t, change);
    const missing = ["proposal", "specs", "design"].filter(
      (a) => (status.artifactPaths[a]?.existingOutputPaths.length ?? 0) === 0,
    );
    if (missing.length > 0) return `o agente não escreveu: ${missing.join(", ")}`;
    // A baseline documents what exists, so it has no tasks; the agent sometimes writes one anyway (D9).
    for (const file of status.artifactPaths.tasks?.existingOutputPaths ?? []) {
      rmSync(resolveInside([join(ws.rootPath, "openspec", "changes", change)], file), { force: true });
    }
    const designFile = status.artifactPaths.design!.existingOutputPaths[0]!;
    if (parseEvidenceTable(readFileSync(resolveInside([ws.rootPath], designFile), "utf8")).length === 0) {
      return "o design.md não tem a tabela de evidências";
    }
    const report = await this.openspec.validate(t, change);
    const item = report.items.find((i) => i.id === change);
    if (item && !item.valid) {
      return `openspec validate: ${item.issues.map((i) => i.message).join("; ")}`;
    }
    const detail = await this.openspec.showChange(t, change);
    if (detail.deltas.some((d) => d.operation !== "ADDED")) return "uma baseline só pode adicionar requisitos";
    if (!detail.deltas.some((d) => d.spec === cap)) return `a spec deve ficar em specs/${cap}/spec.md`;
    // Without a Purpose, archive writes a "TBD" placeholder into the main spec (D9).
    const specFile = status.artifactPaths.specs!.existingOutputPaths.find((f) => f.endsWith(`specs/${cap}/spec.md`));
    if (specFile && !hasPurpose(readFileSync(resolveInside([ws.rootPath], specFile), "utf8"))) {
      return "a spec não tem a seção ## Purpose";
    }
    return undefined;
  }

  // --- 8.6 / 8.7 review ------------------------------------------------------

  async review(jobId: string, cap: string): Promise<BaselineReview> {
    const job = this.job(jobId);
    const c = this.#capIn(job, cap, ["pronta", "aprovada"]);
    const ws = this.workspaces.get(job.workspaceId);
    const change = c.changeName ?? baselineName(cap);
    const status = await this.openspec.status(target(ws), change);
    const read = (a: string) =>
      (status.artifactPaths[a]?.existingOutputPaths ?? []).map((f) => ({
        path: relative(status.changeRoot, f),
        content: readFileSync(resolveInside([ws.rootPath], f), "utf8"),
      }));
    const files = [...read("proposal"), ...read("specs"), ...read("design")];
    const spec = files.find((f) => f.path === `specs/${cap}/spec.md`)?.content ?? "";
    const design = files.find((f) => f.path === "design.md")?.content ?? "";
    return { capability: cap, change, requirements: reviewRequirements(spec, design), files };
  }

  approve(jobId: string, cap: string): OnboardingJob {
    const job = this.job(jobId);
    this.#capIn(job, cap, ["pronta"]);
    this.repo.updateCapability(jobId, cap, { status: "aprovada" });
    this.#publish(job);
    return this.job(jobId);
  }

  /** Asks for an adjustment in the baseline's own session; it returns to review afterwards. */
  async adjust(jobId: string, cap: string, request: string): Promise<OnboardingJob> {
    const job = this.job(jobId);
    const c = this.#capIn(job, cap, ["pronta", "aprovada"]);
    const ws = this.workspaces.get(job.workspaceId);
    const change = c.changeName ?? baselineName(cap);
    const status = await this.openspec.status(target(ws), change);
    const files = ["proposal", "specs", "design"].flatMap((a) => status.artifactPaths[a]?.existingOutputPaths ?? []);
    this.repo.updateCapability(jobId, cap, { status: "gerando", error: null });
    this.#publish(job);
    const done = this.#runAndCheck(ws, job, cap, change, buildAdjustPrompt(`baseline ${cap}`, files, request))
      .catch((err) => this.repo.updateCapability(jobId, cap, { status: "falhou", error: (err as Error).message }))
      .finally(() => this.#publish(job));
    this.#track(done);
    return this.job(jobId);
  }

  /** Removes the baseline change from disk; other capabilities are untouched (spec: "Descartar"). */
  discard(jobId: string, cap: string): OnboardingJob {
    const job = this.job(jobId);
    const c = this.#capIn(job, cap, ["pronta", "aprovada", "falhou", "cancelada"]);
    const ws = this.workspaces.get(job.workspaceId);
    const changes = join(ws.rootPath, "openspec", "changes");
    const dir = resolveInside([changes], join(changes, c.changeName ?? baselineName(cap)));
    if (dir !== changes) rmSync(dir, { recursive: true, force: true });
    this.repo.updateCapability(jobId, cap, { status: "descartada", error: null });
    this.#publish(job);
    return this.job(jobId);
  }

  /**
   * Archives every approved baseline, one at a time, so one failure leaves the others
   * archived (spec: "Archive parcial", "Falha no archive de uma baseline").
   */
  async archive(jobId: string): Promise<ArchiveOutcome[]> {
    const job = this.job(jobId);
    const ws = this.workspaces.get(job.workspaceId);
    const outcomes: ArchiveOutcome[] = [];
    for (const cap of job.capabilities.filter((c) => c.status === "aprovada")) {
      const change = cap.changeName ?? baselineName(cap.name);
      try {
        await this.openspec.archive(target(ws), change);
        this.repo.updateCapability(jobId, cap.name, { status: "arquivada", error: null });
        outcomes.push({ capability: cap.name, change, ok: true });
      } catch (err) {
        const message = (err as Error).message;
        this.repo.updateCapability(jobId, cap.name, { error: `archive falhou: ${message}` });
        outcomes.push({ capability: cap.name, change, ok: false, error: message });
      }
    }
    this.#publish(job);
    return outcomes;
  }

  // --- internals ---------------------------------------------------------------

  #start(ws: Workspace, change: string, prompt: BuiltPrompt, writable: string[] = []) {
    const members = ws.members.map((m) => m.path);
    return this.runner.start({
      workspaceId: ws.id,
      change,
      directory: ws.rootPath,
      text: prompt.text,
      system: prompt.system,
      permission: sessionPermissions(ws.rootPath, members, writable),
      guard: new WriteGuard(members, join(ws.rootPath, "openspec")),
    });
  }

  #inStatus(jobId: string, status: OnboardingJob["status"]): OnboardingJob {
    const job = this.job(jobId);
    if (job.status !== status) throw new OnboardingStateError(`o onboarding está em "${job.status}", não em "${status}"`);
    return job;
  }

  #capIn(job: OnboardingJob, cap: string, allowed: CapabilityStatus[]): Capability {
    const c = job.capabilities.find((x) => x.name === cap);
    if (!c) throw new WorkspaceInputError(`capacidade desconhecida: ${cap}`);
    if (!allowed.includes(c.status)) {
      throw new OnboardingStateError(`${cap} está "${c.status}"; a ação exige ${allowed.map((s) => `"${s}"`).join(" ou ")}`);
    }
    return c;
  }

  #track(p: Promise<unknown>): void {
    const tracked = p.catch(() => undefined).finally(() => this.#pending.delete(tracked));
    this.#pending.add(tracked);
  }

  #publish(job: OnboardingJob): void {
    this.#publishId(job.workspaceId, job.id);
  }

  #publishId(workspaceId: string, jobId: string): void {
    this.events.publish({ type: "onboarding-changed", workspaceId, jobId });
  }
}

/** Whether a spec has a `## Purpose` section with some text in it. */
export function hasPurpose(spec: string): boolean {
  const m = /^## Purpose[ \t]*\n([\s\S]*?)(?=^## |(?![\s\S]))/m.exec(spec);
  return !!m && m[1]!.trim().length > 0;
}

export function baselineName(cap: string): string {
  return `baseline-${cap}`;
}

/** Why a capability list cannot be used, or undefined when it is fine. */
function listProblem(caps: readonly CapabilityDraft[], ws: Workspace): string | undefined {
  const names = new Set<string>();
  const members = new Set(ws.members.map((m) => m.name));
  for (const cap of caps) {
    if (!CAPABILITY_NAME.test(cap.name)) return `nome inválido (use kebab-case): ${cap.name}`;
    if (names.has(cap.name)) return `capacidade repetida: ${cap.name}`;
    names.add(cap.name);
    const unknown = cap.locations.find((l) => !members.has(l.member));
    if (unknown) return `${cap.name} aponta para um membro desconhecido: ${unknown.member}`;
  }
  return undefined;
}

function target(ws: Workspace): Target {
  return { cwd: ws.rootPath, store: ws.storeId ?? undefined };
}
